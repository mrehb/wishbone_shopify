def width(text, gap=1):
    return max(0, len(text)*(5+gap)-gap)

def svg(text, on='#0F1014', off=None, pitch=10, r=4.1, gap=1, cls='dm', title=None):
    """Render text as round dots. `off` draws the unlit matrix too, like a display."""
    text = text.upper(); cols = width(text, gap); out = []
    for i, ch in enumerate(text):
        g = G.get(ch, G[' ']); x0 = i*(5+gap)
        for k, c in enumerate(g):
            x, y = x0 + k % 5, k // 5
            if c == '#': out.append(f'<circle cx="{x*pitch+pitch/2:g}" cy="{y*pitch+pitch/2:g}" r="{r:g}"/>')
            elif off: out.append(f'<circle fill="{off}" cx="{x*pitch+pitch/2:g}" cy="{y*pitch+pitch/2:g}" r="{r:g}"/>')
    W, H = cols*pitch, 7*pitch
    t = f'<title>{escape(title or text)}</title>'
    return (f'<svg class="{cls}" viewBox="0 0 {W:g} {H:g}" role="img" xmlns="http://www.w3.org/2000/svg">'
            f'{t}<g fill="{on}">' + "".join(out) + '</g></svg>')
